PAT_START = re.compile(r'^\s*(?:Sys\.)?set\s*\(\s*"mode"\s*,\s*"validate"')
PAT_END   = re.compile(r'^\s*(?:Sys\.)?set\s*\(\s*"mode"\s*,\s*"evaluate"')
PAT_UNIT  = re.compile(r'^>\s*val it = \(\) : unit\s*$')
PAT_PLAN  = re.compile(r'^\s*Sys\.(?:plan|planEx)\b')


def strip_license(text):
    lines = text.splitlines(keepends=True)
    if not lines or not lines[0].startswith("(*"):
        return text
    depth = 0
    end = 0
    for i, ln in enumerate(lines):
        depth += ln.count("(*") - ln.count("*)")
        if depth == 0:
            end = i + 1
            break
    return "".join(lines[end:])


def strip_validate_sections(text):
    out, inside, drop_next_unit = [], False, False
    for ln in text.splitlines(keepends=True):
        if drop_next_unit:
            drop_next_unit = False
            if PAT_UNIT.match(ln):
                continue
        if not inside and PAT_START.match(ln):
            inside = True
            continue
        if inside:
            if PAT_END.match(ln):
                inside = False
                drop_next_unit = True
                continue
            continue
        out.append(ln)
    return "".join(out)


def strip_plan(text):
    out, drop_output = [], False
    for ln in text.splitlines(keepends=True):
        if drop_output:
            if ln.startswith(">"):
                continue
            drop_output = False
        if PAT_PLAN.match(ln):
            drop_output = True
            continue
        out.append(ln)
    return "".join(out)


with open(SRC) as fh:
    text = strip_plan(strip_validate_sections(strip_license(fh.read())))
text = text.lstrip("\n").rstrip() + "\n"

body = HEADER
for rep in range(COPIES):
    tag = f"relational.smli (copy {rep + 1}/{COPIES})"
    body += f"(*) Begin {tag} *)\nSys.clearEnv ();\n> val it = () : unit\n{text}(*) End {tag} *)\n\n"

with open(OUT, "w") as fh:
    fh.write(body)
print(f"  {OUT}: {len(body):>8d} bytes, {body.count(chr(10)):>5d} lines, {COPIES} copies")
